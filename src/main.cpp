#include "Lexer.h"     //подключаем наш лексический анализатор для разбора текста
#include "Analyzer.h"  //подключаем модуль анализатора для сбора статистики
#include <fstream>     //подключаем работу с файловыми потоками (std::ifstream)
#include <sstream>     //подключаем работу со строковыми потоками (std::ostringstream)
#include <iostream>    //подключаем стандартный ввод-вывод (std::cout, std::cerr)

#ifdef _WIN32          //условная компиляция: если целевая ОС - Windows
#include <windows.h>   //подключаем Windows API для настройки консоли
#endif

//вспомогательная функция для чтения содержимого файла по пути в виде одной большой строки
static std::string readFile(const std::string& path) {
    std::ifstream in(path, std::ios::binary); //открываем файл в бинарном режиме
    if (!in) throw std::runtime_error("Не удалось открыть файл: " + path); //если файл не открылся, выбрасываем ошибку
    std::ostringstream ss; //создаем строковый поток
    ss << in.rdbuf(); //перекладываем буфер файла в поток
    return ss.str(); //возвращаем считанный текст в виде строки
}

//главная функция программы - точка старта при запуске из консоли
int main(int argc, char** argv) {
#ifdef _WIN32          //если запущено на Windows
    SetConsoleOutputCP(CP_UTF8); //устанавливаем кодировку UTF-8 для вывода в консоль
    SetConsoleCP(CP_UTF8);       //устанавливаем кодировку UTF-8 для ввода
#endif

    //проверяем, передал ли пользователь хотя бы один файл аргументом командной строки
    if (argc < 2) {
        std::cerr << "Использование: " << argv[0]
                  << " <файл1.swift> [файл2.swift ...]\n"; // Выводим инструкцию по использованию
        return 1; //завершаем программу с кодом ошибки
    }

    Analyzer analyzer;     //создаем объект анализатора для сбора статистики со всех файлов
    int errorCount = 0;    //счетчик обнаруженных ошибок

    //запускаем цикл обработки всех файлов, переданных через аргументы командной строки (начиная с индекса 1)
    for (int i = 1; i < argc; ++i) {
        std::string filename = argv[i]; //получаем путь к текущему файлу
        try {
            std::string source = readFile(filename); //читаем текст файла
            Lexer lexer(source, filename); //инициализируем лексер исходным кодом и именем файла
            Token t; //переменная для хранения текущего токена
            //крутим цикл, пока лексер выдает новые токены
            while (lexer.nextToken(t)) {
                analyzer.add(t); //передаем токен в анализатор для учета
                if (t.type == TokenType::UNKNOWN) { //если лексер нашел неизвестный символ (ошибку)
                    std::cerr << "Ошибка: неизвестный символ '" << t.value
                              << "' в " << t.file << ":" << t.line
                              << ":" << t.column << "\n"; //выводим детали ошибки в поток ошибок
                    errorCount++; //увеличиваем счетчик ошибок
                }
            }
        } catch (const std::exception& e) { //ловим фатальные исключения (например, незакрытая строка или комментарий)
            std::cerr << "Фатальная ошибка: " << e.what() << "\n"; //выводим текст ошибки
            errorCount++; //увеличиваем счетчик ошибок
        }
    }

    analyzer.report(std::cout); //выводим итоговый отчет со статистикой в стандартный вывод

    if (errorCount > 0) { //если за время работы были найдены ошибки...
        std::cout << "\nОбнаружено ошибок: " << errorCount << "\n";
        return 2; //возвращаем код ошибки 2
    }
    return 0; //возвращаем 0 в случае успешного завершения
}