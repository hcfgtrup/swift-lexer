#pragma once//защита от повторного включения заголовочного файла
#include <string>//подключаем строки, они нужны для хранения текста лексемы

enum class TokenType {//перечисление всех типов лексем, которые умеет различать наш лексер
    KEYWORD,//ключевое слово: let, var, if, #available и т.д.
    IDENTIFIER,//идентификатор: имя переменной, функции, типа
    NUMBER,//число: целое, дробное, hex, oct, bin, hex-float
    STRING,//строковый литерал в кавычках
    OPERATOR,//оператор: +, ==, ->, ??, ...
    DELIMITER,//разделитель: ( ) { } [ ] , ; : .
    UNKNOWN//неизвестный символ, это лексическая ошибка
};

struct Token {//структура одной лексемы, её отдаёт лексер и принимает анализатор
    TokenType type;//тип лексемы, нужен для статистики
    std::string value;//текст лексемы, нужен для отчёта и для проверки
    std::string file;//имя файла, нужно для отчёта по идентификаторам
    int line;//номер строки, нужен для отчёта по идентификаторам
    int column;//номер колонки, нужен для диагностики ошибок
};