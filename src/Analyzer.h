#pragma once //защита от повторного включения заголовочного файла
#include "Token.h" //подключаем описание структуры Token и типов токенов
#include <map> //подключаем контейнер std::map для упорядоченных ассоциативных массивов
#include <vector> //подключаем динамические массивы std::vector
#include <string> //подключаем строки
#include <iostream> //подключаем потоки ввода-вывода (std::ostream)

//структура для хранения информации о конкретном вхождении идентификатора
struct IdentifierInfo {
    std::string file; //имя файла, где встретился идентификатор
    int line;         //номер строки в этом файле
};

//сбор общей статистики и построение отчетов
class Analyzer {
public:
    long long total = 0; //общее количество всех успешно распознанных токенов
    std::map<TokenType, long long> counts; //словарь для подсчета абсолютной частоты каждого типа токена
    std::map<std::string, std::vector<IdentifierInfo>> identifiers; //словарь идентификаторов: имя -> список мест использования(по алфавиту автоматически)

    //метод для добавления нового токена в общую статистику анализатора
    void add(const Token& t) {
        total++; //увеличиваем счетчик общего числа лексем на единицу
        counts[t.type]++; //увеличиваем счетчик частоты конкретного типа лексемы
        //если пришедший токен является идентификатором
        if (t.type == TokenType::IDENTIFIER) {
            //добавляем информацию о его расположении (файл и строка) в вектор по имени идентификатора
            identifiers[t.value].push_back({t.file, t.line});
        }
    }

    //вспомогательный статический метод для перевода внутреннего типа токена в читаемую строку на русском языке
    static std::string typeName(TokenType t) {
        switch (t) { //проверяем переданный тип токена
            case TokenType::KEYWORD:    return "Ключевое слово"; //если ключевое слово
            case TokenType::IDENTIFIER: return "Идентификатор"; //если идентификатор
            case TokenType::NUMBER:     return "Число";          //если число
            case TokenType::STRING:     return "Строка";         //если строка
            case TokenType::OPERATOR:   return "Оператор";       //если оператор
            case TokenType::DELIMITER:  return "Разделитель";    //если разделитель
            case TokenType::UNKNOWN:    return "Ошибка";         //если неизвестный символ (ошибка)
        }
        return "?"; //возвращаем знак вопроса на случай непредвиденных ситуаций
    }

    //метод для генерации и вывода итогового отчета в заданный выходной поток (например, в std::cout)
    void report(std::ostream& os) const {
        os << "ОБЩАЯ СТАТИСТИКА\n"; //выводим заголовок блока общей статистики
        os << "Всего лексем: " << total << "\n\n"; //выводим общее число всех лексем

        os << "ПО ТИПАМ\n"; // Выводим заголовок блока статистики по типам
        //задаем фиксированный порядок вывода типов лексем в отчете
        std::vector<TokenType> order = {
            TokenType::KEYWORD, TokenType::IDENTIFIER, TokenType::NUMBER,
            TokenType::STRING, TokenType::OPERATOR, TokenType::DELIMITER,
            TokenType::UNKNOWN
        };
        //проходим в цикле по каждому типу токена в заданном порядке
        for (auto t : order) {
            auto it = counts.find(t); //ищем текущий тип в словаре частот
            long long c = (it == counts.end()) ? 0 : it->second; //если не найден, количество равно 0, иначе берем сохраненное число
            double pct = total ? (100.0 * c / total) : 0.0; //вычисляем относительную частоту в процентах (избегая деления на ноль)
            os << typeName(t) << ": " << c << " (" << pct << "%)\n"; //выводим название типа, абсолютную и относительную частоту
        }
        os << "\n"; //добавляем пустую строку для красоты

        os << "ИДЕНТИФИКАТОРЫ(лексикографический порядок)\n"; //заголовок списка идентификаторов
        //проходим по всем уникальным идентификаторам (std::map сам гарантирует алфавитный/лексикографический порядок ключей)
        for (const auto& [name, occs] : identifiers) {
            os << name << " — " << occs.size() << " вхожд.\n"; //выводим имя идентификатора и общее количество его вхождений
            //проходим по каждому месту, где встречался данный идентификатор
            for (const auto& o : occs) {
                os << "    " << o.file << ":" << o.line << "\n"; //выводим название файла и номер строки для каждого вхождения с отступом
            }
        }
    }
};